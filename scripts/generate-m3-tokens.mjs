import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  argbFromHex,
  hexFromArgb,
  themeFromSourceColor,
} from '@material/material-color-utilities'

const __dirname = dirname(fileURLToPath(import.meta.url))
const outFile = resolve(__dirname, '../src/styles/m3/color.css')

const SEED = '#006A68'
const theme = themeFromSourceColor(argbFromHex(SEED))

const ROLE_KEYS = [
  'primary',
  'on-primary',
  'primary-container',
  'on-primary-container',
  'secondary',
  'on-secondary',
  'secondary-container',
  'on-secondary-container',
  'tertiary',
  'on-tertiary',
  'tertiary-container',
  'on-tertiary-container',
  'error',
  'on-error',
  'error-container',
  'on-error-container',
  'surface',
  'on-surface',
  'surface-dim',
  'surface-bright',
  'surface-container-lowest',
  'surface-container-low',
  'surface-container',
  'surface-container-high',
  'surface-container-highest',
  'on-surface-variant',
  'outline',
  'outline-variant',
  'inverse-surface',
  'inverse-on-surface',
  'inverse-primary',
  'surface-tint',
]

function toCssVar(key) {
  return key.replace(/([A-Z])/g, '-$1').toLowerCase()
}

const SURFACE_CONTAINERS = {
  light: {
    'surface-container-lowest': 100,
    'surface-container-low': 96,
    'surface-container': 94,
    'surface-container-high': 92,
    'surface-container-highest': 90,
    'surface-dim': 87,
    'surface-bright': 98,
  },
  dark: {
    'surface-container-lowest': 4,
    'surface-container-low': 10,
    'surface-container': 12,
    'surface-container-high': 17,
    'surface-container-highest': 22,
    'surface-dim': 6,
    'surface-bright': 24,
  },
}

function block(variant, label) {
  const json = theme.schemes[variant].toJSON()
  const entries = Object.entries(json)
  const neutral = theme.palettes.neutral
  for (const [key, tone] of Object.entries(SURFACE_CONTAINERS[variant])) {
    if (!(key in json)) entries.push([key, neutral.tone(tone)])
  }
  const lines = entries.map(([key, color]) => {
    return `  --md-sys-color-${toCssVar(key)}: #${hexFromArgb(color).slice(1)};`
  })
  return `[data-theme='${label}'], .v-theme--${label} {\n${lines.join('\n')}\n}\n`
}

const css = `/* AUTO-GENERATED by scripts/generate-m3-tokens.mjs from seed ${SEED} */
/* Do not edit by hand — re-run the script instead. */

${block('light', 'light')}
${block('dark', 'dark')}
`

mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(outFile, css, 'utf8')
console.log(`Wrote ${outFile}`)
